import { Router } from 'express';
import { fieldsRouter } from './fields';
import { keysRouter } from './keys';
import { registrationRouter } from './registration';
import { usersRouter } from './users';
import { authRouter } from './auth';
import { quizzesRouter } from './quizzes';
import { statsRouter } from './stats';
import { achievementsRouter } from './achievements';
import { settingsRouter } from './settings';
import { presenceRouter } from './presence';
import { forumRouter } from './forum';
import { chatRouter } from './chat';
import { photosRouter } from './photos';
import { imageReviewsRouter } from './image-reviews';
import { tycoonRouter } from './tycoon';
import { requireAuth, requireAdmin } from '../middleware/auth';

export const apiRouter = Router();

apiRouter.use('/fields', fieldsRouter);
apiRouter.use('/register', registrationRouter);
apiRouter.use('/users', usersRouter);
apiRouter.use('/keys', requireAuth, requireAdmin, keysRouter);
apiRouter.use('/auth', authRouter);
apiRouter.use('/quizzes', quizzesRouter);
apiRouter.use('/stats', statsRouter);
apiRouter.use('/achievements', achievementsRouter);
apiRouter.use('/settings', settingsRouter);
apiRouter.use('/image-reviews', requireAuth, requireAdmin, imageReviewsRouter);
apiRouter.use('/photos', requireAuth, requireAdmin, photosRouter);
apiRouter.use('/presence', presenceRouter);
apiRouter.use('/forum', requireAuth, forumRouter);
apiRouter.use('/chat', requireAuth, chatRouter);
apiRouter.use('/tycoon', requireAuth, tycoonRouter);
